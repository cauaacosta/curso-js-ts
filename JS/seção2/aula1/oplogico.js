/*
Operadores Lógicos
&& -> AND -> E // Todas expressões precisam ser verdadeiras para retornar true
|| -> OR -> OU // Se uma expressão for verdadeira retorna true
! -> NOT -> NÂO // Inverte o resultado e retorna o valor contrário
*/
const expressaoAnd = true && true && true
console.log(expressaoAnd);

const expressaoOR = true || false || false
console.log(expressaoOR);

const expressaoNOT = true || false || false
console.log(!expressaoNOT); 